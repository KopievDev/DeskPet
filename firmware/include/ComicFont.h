inline uint16_t nextCodepoint(const char*& input) {
    const uint8_t a = static_cast<uint8_t>(*input++);
    if (a < 0x80u) return a;
    if ((a & 0xE0u) == 0xC0u && *input != '\0') {
        const uint8_t b = static_cast<uint8_t>(*input++);
        if ((b & 0xC0u) != 0x80u) return '?';
        return static_cast<uint16_t>(((a & 0x1Fu) << 6) | (b & 0x3Fu));
    }
    return '?'; // phrase catalogue is uppercase Russian + ASCII punctuation
}

inline uint16_t width(const char* text) {
    uint16_t count = 0;
    while (*text != '\0') {
        nextCodepoint(text);
        ++count;
    }
    return count * 8;
}

inline void draw(lgfx::LGFX_Sprite& canvas, int left, int top,
                 const char* text, uint16_t color) {
    while (*text != '\0') {
        const uint16_t codepoint = nextCodepoint(text);
        if (codepoint == ' ') {
            left += 8;
            continue;
        }
        const Glyph* found = nullptr;
        for (const auto& glyph : kGlyphs) {
            if (glyph.codepoint == codepoint) {
                found = &glyph;
                break;
            }
        }
        if (found) {
            for (uint8_t y = 0; y < 12; ++y) {
                const uint8_t bits = found->rows[y];
                for (uint8_t x = 0; x < 8; ++x) {
                    if ((bits & (0x80u >> x)) != 0u) {
                        canvas.drawPixel(left + x, top + y, color);
                    }
                }
            }
        }
        left += 8;
    }
}
